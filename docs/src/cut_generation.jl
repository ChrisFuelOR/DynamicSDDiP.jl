# # Configuring the cut generation

# As mentioned in [Setting algorithmic parameters](params.md), we can choose between four general types of cut generation approaches, depending on the dual problem that is solved in the backward pass of SDDiP.
# For each approach, there exists a dedicated struct inheriting from `DynamicSDDiP.AbstractDualityRegime`.

# ## Benders cuts

using DynamicSDDiP
