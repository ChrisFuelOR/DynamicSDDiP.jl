# Using this type of struct to define a `duality_regime` within `algo_params` (see [Setting algorithmic parameters](params.md)) means that standard **Benders cuts** are generated by solving the LP duals of the subproblems.


# ## Strengthened Benders cuts

using DynamicSDDiP
